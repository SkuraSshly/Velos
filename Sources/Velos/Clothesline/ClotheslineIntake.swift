/// 接收剪贴板图片：别的软件、浏览器里复制的图片（或访达里复制的图片文件）也挂到晾衣绳上。
///
/// 设置里打开才工作（默认关）。macOS 没有「剪贴板变了」的通知，只能定时看一眼剪贴板的变化计数
/// （一个整数，不读内容），每秒两次；计数变了才读这一次的内容。关掉时计时器也停掉。
/// 跳过：Velos 自己复制的、密码管理器标记为私密 / 临时的内容。
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    /// Velos 自己放进剪贴板的内容带这个标记
    static let ownType = NSPasteboard.PasteboardType("local.velos.copied")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        ownType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastCount = 0

    private init() {}

    func setRunning(_ running: Bool) {
        if running { start() } else { stop() }
    }

    private func start() {
        guard timer == nil else { return }
        lastCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardWatcher.shared.check() }
        }
        timer.tolerance = 0.2   // 允许系统把它和别的唤醒合并，更省电
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.capture.notice("晾衣绳：开始接收剪贴板图片")
    }

    private func stop() {
        guard let timer else { return }
        timer.invalidate()
        self.timer = nil
        Log.capture.notice("晾衣绳：停止接收剪贴板图片")
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        let items = pasteboard.pasteboardItems ?? []
        guard !items.isEmpty, items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) else { return }
        ClotheslineIntake.hang(items)
    }
}

/// 把收到的东西挂上绳：图片文件、录屏文件、图片数据
@MainActor
enum ClotheslineIntake {
    /// 太大的图片数据不收（例如复制了一张几百 MB 的图）
    private static let maxBytes = 60 * 1024 * 1024

    static func hang(_ items: [NSPasteboardItem]) {
        var count = 0
        for item in items {
            if let raw = item.string(forType: .fileURL), let url = URL(string: raw), url.isFileURL {
                let file = url.standardizedFileURL.resolvingSymlinksInPath()
                let ext = file.pathExtension.lowercased()
                if ScreenshotHistory.imageExtensions.contains(ext) || ScreenshotHistory.linkedExtensions.contains(ext) {
                    ScreenshotHistory.shared.record(file: file)
                    count += 1
                    continue
                }
                // 访达里的普通文件也会带一个图标图片，那不算图片
                continue
            }
            if let data = imageData(from: item) {
                ScreenshotHistory.shared.record(imageData: data)
                count += 1
            }
        }
        if count > 0 {
            Log.capture.notice("晾衣绳：挂上 \(count) 张")
            ClotheslineController.shared.showNextCapture(near: ClotheslineController.screenUnderPointer()?.frame ?? .zero)
        }
    }

    /// 从访达挂上来的文件（「打开方式 → Velos」、拖到程序坞里的 Velos 图标上）：图片存一份，录屏、GIF 存替身
    static func hang(files urls: [URL]) {
        let usable = urls.filter { url in
            let ext = url.pathExtension.lowercased()
            return ScreenshotHistory.imageExtensions.contains(ext) || ScreenshotHistory.linkedExtensions.contains(ext)
        }
        guard !usable.isEmpty else { return NSSound.beep() }
        for url in usable { ScreenshotHistory.shared.record(file: url) }
        Log.capture.notice("晾衣绳：从访达挂上 \(usable.count) 个")
        ClotheslineController.shared.showNextCapture(near: ClotheslineController.screenUnderPointer()?.frame ?? .zero)
    }

    private static func imageData(from item: NSPasteboardItem) -> Data? {
        for type in [NSPasteboard.PasteboardType.png, .tiff, .init(UTType.jpeg.identifier),
                     .init(UTType.heic.identifier), .init(UTType.webP.identifier)] {
            if let data = item.data(forType: type), !data.isEmpty, data.count <= maxBytes { return data }
        }
        return nil
    }
}

/// 绳子下面的一层：也是拖进来的图能放下的地方。平时不拦鼠标（由面板决定什么时候接收），
/// 拖着图片到屏幕顶部时绳子下来接，松手就挂上
final class ClotheslineDropSurface: NSView {
    var onDrop: (([NSPasteboardItem]) -> Void)?
    /// 拖着的图进来 / 出去：绳子显示「松手挂到这里」
    var onDragChange: ((Bool) -> Void)?

    override init(frame frameRect: NSRect) {
        super.init(frame: frameRect)
        registerForDraggedTypes([.fileURL, .tiff, .png])
    }

    required init?(coder: NSCoder) { fatalError("init(coder:) has not been implemented") }

    /// 只看类型，不读内容（每次移动都读一遍图片太费）
    private func carriesPicture(_ info: NSDraggingInfo) -> Bool {
        // 从绳上自己拖出来的不算
        if info.draggingSource is ClotheslineGrabView { return false }
        let types = info.draggingPasteboard.types ?? []
        return types.contains(.fileURL) || types.contains(.tiff) || types.contains(.png)
    }

    override func draggingEntered(_ sender: NSDraggingInfo) -> NSDragOperation {
        guard carriesPicture(sender) else { return [] }
        onDragChange?(true)
        return .copy
    }

    override func draggingUpdated(_ sender: NSDraggingInfo) -> NSDragOperation {
        carriesPicture(sender) ? .copy : []
    }

    override func draggingExited(_ sender: NSDraggingInfo?) {
        onDragChange?(false)
    }

    override func prepareForDragOperation(_ sender: NSDraggingInfo) -> Bool {
        carriesPicture(sender)
    }

    override func performDragOperation(_ sender: NSDraggingInfo) -> Bool {
        onDragChange?(false)
        let items = sender.draggingPasteboard.pasteboardItems ?? []
        guard !items.isEmpty else { return false }
        onDrop?(items)
        return true
    }
}
